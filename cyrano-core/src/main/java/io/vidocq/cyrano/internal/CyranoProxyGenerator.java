package io.vidocq.cyrano.internal;

import java.lang.classfile.ClassFile;
import java.lang.classfile.TypeKind;
import java.lang.constant.ClassDesc;
import java.lang.constant.MethodTypeDesc;
import java.lang.invoke.MethodHandle;
import java.lang.invoke.MethodHandles;
import java.lang.invoke.MethodType;
import java.lang.reflect.Method;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;

import static java.lang.constant.ConstantDescs.CD_Object;
import static java.lang.constant.ConstantDescs.CD_int;
import static java.lang.constant.ConstantDescs.INIT_NAME;
import static java.lang.constant.ConstantDescs.MTD_void;

/**
 * Proxy generator via JDK 25 Class-File API (JEP 484) — produces a class
 * concrete name {@code Cyrano$<SimpleName>} which implements the client interface.
 *
 * <p>No {@link java.lang.reflect.Proxy} dynamic proxy, no ASM or Byte Buddy.
 * The generated class is defined via {@link MethodHandles.Lookup#defineClass(byte[])}
 * in the package of the client interface. Benefits: AOT compatible (GraalVM, Leyden CDS),
 * readable stack traces, no {@code setAccessible(true)}.</p>
 *
 * <p>Anatomy of a proxy generated for a {@code com.acme.UserService} interface:</p>
 * <pre>
 *   package com.acme;                             // package of the interface
 *   public final class Cyrano$UserService implements com.acme.UserService, Closeable {
 *       private final MethodHandle invoker;       // CyranoInvocationHandler.invoke, bound
 *       private final Runnable closer;            // CyranoInvocationHandler.markClosed
 *       public Cyrano$UserService(MethodHandle invoker, Runnable closer) { ... }
 *       public String getUser(long id) {
 *           Object[] args = new Object[] { Long.valueOf(id) };
 *           try {
 *               return (String) invoker.invokeExact((Object) this, 0, args);
 *           } catch (RuntimeException | Error e) { throw e; }
 *             catch (Throwable e) { throw new RuntimeException(e); }
 *       }
 *       public void close() { closer.run(); }
 *   }
 * </pre>
 *
 * <p><b>Java Modules.</b> The proxy only refers to {@code java.base} types besides the interface's
 * own signatures, so the host module needs neither to read cyrano-core nor to see its internal
 * package (BUG-20261008-02). The one requirement on the host module is the one the error message
 * names: {@code opens <package> to io.vidocq.cyrano.core}, which lets cyrano-core define a class in
 * that package. cyrano-core adds the read edge to the host module itself. Clients generated by
 * cyrano-processor need no {@code opens} at all.</p>
 *
 * <p>The index passed to {@link CyranoInvocationHandler#invoke(Object, int, Object[])} corresponds to
 * the iteration order of {@code Map<Method, RequestSpec>} (which is a {@link
 * java.util.LinkedHashMap LinkedHashMap} — stable insertion order.</p>
 */
public final class CyranoProxyGenerator {

    private static final ClassDesc CD_MethodHandle =
            MethodHandle.class.describeConstable().orElseThrow();
    private static final ClassDesc CD_Runnable = Runnable.class.describeConstable().orElseThrow();
    private static final String FIELD_INVOKER = "invoker";
    private static final String FIELD_CLOSER = "closer";
    /** {@code (Object proxy, int methodIndex, Object[] args) -> Object}, the shape of {@code invoke}. */
    private static final MethodType INVOKE_TYPE =
            MethodType.methodType(Object.class, Object.class, int.class, Object[].class);
    private static final MethodHandle HANDLER_INVOKE;

    static {
        try {
            HANDLER_INVOKE = MethodHandles.lookup().findVirtual(CyranoInvocationHandler.class, "invoke", INVOKE_TYPE);
        } catch (ReflectiveOperationException e) {
            throw new ExceptionInInitializerError(e);
        }
    }
    private static final ClassDesc CD_RuntimeException =
            RuntimeException.class.describeConstable().orElseThrow();
    private static final ClassDesc CD_Error = Error.class.describeConstable().orElseThrow();
    private static final ClassDesc CD_Throwable = Throwable.class.describeConstable().orElseThrow();
    private static final ClassDesc CD_Closeable =
            java.io.Closeable.class.describeConstable().orElseThrow();

    private CyranoProxyGenerator() {
        // utility
    }

    /**
     * Generates a proxy class implementing {@code iface}, registers it in the ClassLoader
     * via {@link MethodHandles.Lookup#defineClass(byte[])} and returns it.
     *
     * <p>Idempotent at content level — caller must hide the result
     * (see {@code CyranoProxyCache}).</p>
     */
    public static Class<?> generate(Class<?> iface, Map<Method, RequestSpec> specs) {
        List<Method> methods = new ArrayList<>(specs.keySet());
        //For inner interfaces, include the chain of enclosing classes in the
        //proxy name — otherwise three interfaces named `SpanResourceClient` in three
        //different outer classes (MP Telemetry TCK case) generate the same proxy
        // `Cyrano$SpanResourceClient` and collide (LinkageError + ClassCastException
        //between tests). `$` in the binary name is replaced by `_` in the suffix to
        //keep a single legible `Cyrano$` separator.
        String pkg = iface.getPackageName();
        String binaryWithoutPkg = pkg.isEmpty() ? iface.getName() : iface.getName().substring(pkg.length() + 1);
        String simpleName = "Cyrano$" + binaryWithoutPkg.replace('$', '_');
        //The proxy is generated in the same package as the target interface in order to be able to
        //implement it even when it is package-private, and to avoid visibility issues
        //between named modules (each module remains responsible for its own
        //proxies). Requires the user module to open its package to cyrano-core
        //(or both are in the unnamed module, test/classpath case).
        String binaryName = pkg.isEmpty() ? simpleName : pkg + "." + simpleName;
        ClassDesc thisClass = ClassDesc.of(binaryName);
        ClassDesc ifaceDesc = iface.describeConstable().orElseThrow();

        byte[] bytes = ClassFile.of().build(thisClass, cb -> {
            cb.withFlags(ClassFile.ACC_PUBLIC | ClassFile.ACC_FINAL | ClassFile.ACC_SUPER);
            //Always implements Closeable — spec MP Rest Client §8.1: all proxies must be Closeable
            cb.withInterfaceSymbols(ifaceDesc, CD_Closeable);
            cb.withSuperclass(CD_Object);
            cb.withField(FIELD_INVOKER, CD_MethodHandle, ClassFile.ACC_PRIVATE | ClassFile.ACC_FINAL);
            cb.withField(FIELD_CLOSER, CD_Runnable, ClassFile.ACC_PRIVATE | ClassFile.ACC_FINAL);

            // Constructor: Cyrano$X(MethodHandle invoker, Runnable closer)
            cb.withMethodBody(INIT_NAME,
                    MethodTypeDesc.of(java.lang.constant.ConstantDescs.CD_void, CD_MethodHandle, CD_Runnable),
                    ClassFile.ACC_PUBLIC,
                    code -> code
                            .aload(0)
                            .invokespecial(CD_Object, INIT_NAME, MTD_void)
                            .aload(0)
                            .aload(1)
                            .putfield(thisClass, FIELD_INVOKER, CD_MethodHandle)
                            .aload(0)
                            .aload(2)
                            .putfield(thisClass, FIELD_CLOSER, CD_Runnable)
                            .return_());

            //One method per scan entry, in insertion order.
            for (int i = 0; i < methods.size(); i++) {
                Method m = methods.get(i);
                emitMethod(cb, thisClass, m, i);
            }

            //close() — spec §8.1: all proxies are Closeable.
            //closer.run() calls handler.markClosed(); after closing, invoke() throws IllegalStateException.
            cb.withMethodBody("close",
                    MethodTypeDesc.of(java.lang.constant.ConstantDescs.CD_void),
                    ClassFile.ACC_PUBLIC | ClassFile.ACC_FINAL,
                    code -> code
                            .aload(0)
                            .getfield(thisClass, FIELD_CLOSER, CD_Runnable)
                            .invokeinterface(CD_Runnable, "run", MTD_void)
                            .return_());
        });

        //privateLookupIn needs cyrano-core to read the host module; a module may add a read edge
        //for itself (BUG-20261008-02). No-op for the unnamed module and for modules already read.
        CyranoProxyGenerator.class.getModule().addReads(iface.getModule());
        try {
            //privateLookupIn gives access to the interface package — lets you define
            //the proxy class in this package, whether public or not. For
            //interfaces of named modules, the user module must open its
            //package to cyrano-core via `opens`.
            MethodHandles.Lookup target = MethodHandles.privateLookupIn(iface, MethodHandles.lookup());
            return defineOrReuse(target, bytes, iface, binaryName);
        } catch (IllegalAccessException e) {
            throw new IllegalStateException(
                    "Cannot define the proxy " + binaryName
                            + " — ensure that the host module opens its package to "
                            + "'io.vidocq.cyrano.core' (opens "
                            + iface.getPackageName() + " to io.vidocq.cyrano.core).", e);
        } catch (ClassNotFoundException e) {
            throw new IllegalStateException(
                    "LinkageError on " + binaryName + " but class not found via Class.forName — "
                            + "ClassLoader inconsistency.", e);
        }
    }

    private static Class<?> defineOrReuse(MethodHandles.Lookup target, byte[] bytes, Class<?> iface, String binaryName)
            throws IllegalAccessException, ClassNotFoundException {
        try {
            return target.defineClass(bytes);
        } catch (LinkageError _) {
            //The proxy has already been defined in this classloader (typically because
            //the CyranoProxyCache cache missed — can happen in
            //Arquillian/ShrinkWrap contexts where several Class<?> objects represent
            //the same interface between successive deployments sharing the same
            //application ClassLoader). Recover the already defined class instead of
            //failing — proxy idempotence is guaranteed by the stable interface signature.
            ClassLoader cl = iface.getClassLoader();
            if (cl == null) cl = ClassLoader.getSystemClassLoader();
            return Class.forName(binaryName, false, cl);
        }
    }

    /**
     * Instantiates a proxy already generated, wired to {@code handler}.
     */
    @SuppressWarnings("unchecked")
    public static <T> T instantiate(Class<?> proxyClass, CyranoInvocationHandler handler) {
        try {
            var ctor = proxyClass.getDeclaredConstructor(MethodHandle.class, Runnable.class);
            Runnable closer = handler::markClosed;
            return (T) ctor.newInstance(HANDLER_INVOKE.bindTo(handler), closer);
        } catch (ReflectiveOperationException e) {
            throw new IllegalStateException("Failed to instantiate proxy " + proxyClass, e);
        }
    }

    private static void emitMethod(java.lang.classfile.ClassBuilder cb, ClassDesc thisClass,
                                   Method m, int methodIndex) {
        ClassDesc retDesc = m.getReturnType().describeConstable().orElseThrow();
        Class<?>[] paramTypes = m.getParameterTypes();
        ClassDesc[] paramDescs = new ClassDesc[paramTypes.length];
        for (int i = 0; i < paramTypes.length; i++) {
            paramDescs[i] = paramTypes[i].describeConstable().orElseThrow();
        }
        MethodTypeDesc methodType = MethodTypeDesc.of(retDesc, paramDescs);

        cb.withMethodBody(m.getName(), methodType,
                ClassFile.ACC_PUBLIC | ClassFile.ACC_FINAL,
                code -> {
                    // Compute slot of the Object[] local variable.
                    //Local slots: 0 = this, then each parameter according to its size.
                    int argsSlot = 1;
                    for (Class<?> p : paramTypes) {
                        argsSlot += (p == long.class || p == double.class) ? 2 : 1;
                    }

                    //Allocate the argument array (one slot per parameter) and fill it with the boxed parameters.
                    code.loadConstant(paramTypes.length);
                    code.anewarray(CD_Object);
                    int slot = 1;
                    for (int i = 0; i < paramTypes.length; i++) {
                        code.dup();
                        code.loadConstant(i);
                        Class<?> p = paramTypes[i];
                        loadAndBox(code, p, slot);
                        code.aastore();
                        slot += (p == long.class || p == double.class) ? 2 : 1;
                    }
                    code.astore(argsSlot);

                    //Protected region: call the bound invoke handle with this proxy, the method index and the arguments.
                    var tryStart = code.newLabel();
                    var tryEnd = code.newLabel();
                    var catchRtEx = code.newLabel();
                    var catchError = code.newLabel();
                    var catchOther = code.newLabel();

                    code.labelBinding(tryStart);
                    code.aload(0);
                    code.getfield(thisClass, FIELD_INVOKER, CD_MethodHandle);
                    code.aload(0);
                    code.loadConstant(methodIndex);
                    code.aload(argsSlot);
                    //invokeExact is signature-polymorphic: the call-site type must be exactly
                    //(Object, int, Object[])Object, the type of the bound handler.invoke.
                    code.invokevirtual(CD_MethodHandle, "invokeExact",
                            MethodTypeDesc.of(CD_Object, CD_Object, CD_int,
                                    CD_Object.arrayType()));
                    emitReturn(code, m.getReturnType(), retDesc);
                    code.labelBinding(tryEnd);

                    //RuntimeException handler: rethrown unchanged.
                    code.labelBinding(catchRtEx);
                    code.athrow();
                    //Error handler: rethrown unchanged.
                    code.labelBinding(catchError);
                    code.athrow();
                    //Any other Throwable (invokeExact declares Throwable) is wrapped in a RuntimeException.
                    code.labelBinding(catchOther);
                    code.astore(argsSlot + 1);
                    code.new_(CD_RuntimeException);
                    code.dup();
                    code.aload(argsSlot + 1);
                    code.invokespecial(CD_RuntimeException, INIT_NAME,
                            MethodTypeDesc.of(java.lang.constant.ConstantDescs.CD_void, CD_Throwable));
                    code.athrow();

                    code.exceptionCatch(tryStart, tryEnd, catchRtEx, CD_RuntimeException);
                    code.exceptionCatch(tryStart, tryEnd, catchError, CD_Error);
                    code.exceptionCatch(tryStart, tryEnd, catchOther, CD_Throwable);
                });
    }

    /**
     * Loads the {@code slot} parameter on the stack and boxes it if primitive,
     * to store it in {@code Object[]}.
     */
    private static void loadAndBox(java.lang.classfile.CodeBuilder code, Class<?> type, int slot) {
        if (!type.isPrimitive()) {
            code.aload(slot);
            return;
        }
        //Typed load (iload for int, short, byte, char and boolean), then Wrapper.valueOf(primitive)
        ClassDesc wrapper = wrapperOf(type);
        code.loadLocal(TypeKind.from(type), slot);
        code.invokestatic(wrapper, "valueOf", MethodTypeDesc.of(wrapper, type.describeConstable().orElseThrow()));
    }

    /**
     * Emits the return code according to the Java type of the method:
     * cast (if necessary) then return/ireturn/lreturn/dreturn/freturn/return.
     */
    private static void emitReturn(java.lang.classfile.CodeBuilder code, Class<?> retType, ClassDesc retDesc) {
        if (retType == void.class) {
            code.pop();
            code.return_();
            return;
        }
        if (retType.isPrimitive()) {
            //Unbox the Object returned by handler.invoke with Wrapper.<primitive>Value()
            ClassDesc wrapper = wrapperOf(retType);
            code.checkcast(wrapper);
            code.invokevirtual(wrapper, retType.getName() + "Value",
                    MethodTypeDesc.of(retType.describeConstable().orElseThrow()));
            code.return_(TypeKind.from(retType));
            return;
        }
        //Reference
        code.checkcast(retDesc);
        code.areturn();
    }

    /** Wrapper class of a primitive type, e.g. {@code java.lang.Integer} for {@code int}. */
    private static ClassDesc wrapperOf(Class<?> primitive) {
        return MethodType.methodType(primitive).wrap().returnType().describeConstable().orElseThrow();
    }
}



